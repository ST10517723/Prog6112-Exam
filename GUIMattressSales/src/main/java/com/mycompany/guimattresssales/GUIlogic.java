private String customerName;
private String productName;
private double price;
private double vat;
private double commission;
private double total;

private void processSale() {
    customerName = txtCustomerName.getText().trim();
    productName = cmbProduct.getSelectedItem().toString();

    if (customerName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter the customer name.");
        return;
    }

    try {
        price = Double.parseDouble(txtPrice.getText().trim());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Please enter a valid price.");
        return;
    }

    ProductCalculations calc = new ProductCalculations(price);
    vat = calc.GetVat();
    commission = calc.GetCommission();
    total = calc.GetTotal();

    String details = "Customer Name: " + customerName + "\n"
            + "Product: " + productName + "\n"
            + "VAT: R " + vat + "\n"
            + "COMMISSION: R " + commission + "\n"
            + "TOTAL: R " + total;

    JOptionPane.showMessageDialog(this, details);
    saveToFile();
}

private void saveToFile() {
    try (PrintWriter writer = new PrintWriter(new FileWriter("data.txt"))) {
        writer.println("DATA LOG");
        writer.println("*********************************");
        writer.println("Customer Name: " + customerName);
        writer.println("Product: " + productName);
        writer.println("VAT: R " + vat);
        writer.println("COMMISSION: R " + commission);
        writer.println("TOTAL: R " + total);
        writer.println("*********************************");
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Could not save to data.txt.");
    }
}


